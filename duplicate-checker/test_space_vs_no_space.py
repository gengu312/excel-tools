"""
测试有空格和无空格数据的重复检测
"""

import pandas as pd

def create_test_data():
    """创建包含有空格和无空格但内容相同的测试数据"""
    
    # 测试数据：包含有空格和无空格的相同内容
    data = {
        '产品名称': [
            'PE发泡衬垫_L35*W35*H30（后下银）',  # 无空格版本
            'PE发泡衬垫_L35*W35*H30 （后下银）',  # 括号前有一个空格
            'PE发泡衬垫_L35*W35*H30  （后下银）', # 括号前有两个空格
            'PE发泡衬垫_L35*W35*H30（后下银）',   # 重复的无空格版本
            'PE发泡衬垫_L35*W35*H30\t（后下银）', # 括号前有制表符
            '塑料垫片_10mm',                    # 无空格
            '塑料垫片_10mm ',                   # 末尾有空格
            '塑料垫片_10mm',                    # 重复的无空格版本
            '塑料 垫片_10mm',                   # 中间有空格
            '橡胶密封圈',                       # 无空格
            '橡胶 密封圈',                      # 中间有空格
            '橡胶  密封圈',                     # 中间有两个空格
            '橡胶密封圈 ',                      # 末尾有空格
            '不锈钢螺丝M6*20',                  # 无空格
            '不锈钢螺丝 M6*20',                 # 中间有空格
            '不锈钢螺丝M6*20 ',                 # 末尾有空格
        ],
        '数量': [10, 15, 8, 12, 5, 20, 25, 18, 22, 30, 35, 28, 32, 40, 45, 38],
        '单价': [2.5, 2.5, 2.5, 2.5, 2.5, 1.2, 1.2, 1.2, 1.2, 3.8, 3.8, 3.8, 3.8, 0.8, 0.8, 0.8]
    }
    
    # 创建DataFrame
    df = pd.DataFrame(data)
    
    # 保存为Excel文件
    filename = 'space_vs_no_space_test.xlsx'
    df.to_excel(filename, index=False)
    
    print(f"测试文件已创建: {filename}")
    print("\n文件内容预览:")
    print(df.to_string(index=False))
    
    print("\n测试说明:")
    print("1. PE发泡衬垫 - 包含无空格、单空格、双空格、制表符等变体")
    print("2. 塑料垫片 - 包含无空格、末尾空格、中间空格等变体")
    print("3. 橡胶密封圈 - 包含无空格、单空格、双空格、末尾空格等变体")
    print("4. 不锈钢螺丝 - 包含无空格、中间空格、末尾空格等变体")
    print("\n这些数据应该被识别为4组重复数据，每组包含不同的空格变体")

if __name__ == "__main__":
    create_test_data()